/**
 * 变动日志。
 *
 * 为什么要有这个页：优惠码站的读者是**回访型**的——银行码每月换、活动码几周一轮。
 * 但市面上排前面的整理页，最多在页首写一个「最後更新 X 月 X 日」，
 * 不告诉你到底变了什么（实测：Google 排第一那篇自己标的更新日是 2026-08-03，
 * 早于我们上线；另一家标题写「每週更新」，页面上找不到上次更新时间）。
 * 「这个月变了什么」是没人做的东西，也是唯一值得让人回来看的东西。
 *
 * 规矩：**只写真的做过的事**，不为了显得勤快而编条目。
 * 没有变动的那周就没有条目——空着比灌水诚实。
 *
 * 「即將失效」不写在这里，由 /changes/ 页面从 brands.ts 的 expiresAt 直接算，
 * 免得手写的日志和真实数据对不上。
 */

